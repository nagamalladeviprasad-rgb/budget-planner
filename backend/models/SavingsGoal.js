import mongoose from "mongoose";

const savingsGoalSchema = new mongoose.Schema({
  userId: { 
    type: mongoose.Schema.Types.ObjectId, 
    ref: "User", 
    required: true 
  },
  name: { 
    type: String, 
    required: true 
  },
  targetAmount: { 
    type: Number, 
    required: true 
  },
  savedAmount: { 
    type: Number, 
    default: 0 
  },
  createdAt: { 
    type: Date, 
    default: Date.now 
  }
});

export default mongoose.model("SavingsGoal", savingsGoalSchema);
